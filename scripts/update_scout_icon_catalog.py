"""Refresh the ID-to-image paths bundled with Scout (Python standard library)."""

import json
from pathlib import Path
from urllib.request import Request, urlopen


BASE = "https://raw.communitydragon.org/latest/plugins/rcp-be-lol-game-data/global/default/"
ROOT = Path(__file__).resolve().parents[1]


def paths(resource):
    request = Request(
        BASE + "v1/" + resource + ".json",
        headers={"User-Agent": "GodSense-Icon-Catalog/1.0"},
    )
    with urlopen(request, timeout=30) as response:
        records = json.load(response)
    result = {}
    prefix = "/lol-game-data/assets/"
    for record in records:
        icon = record.get("iconPath", "")
        if record["id"] > 0 and icon.startswith(prefix):
            result[record["id"]] = icon[len(prefix):].lower()
    if not result:
        raise ValueError("Empty icon catalogue: " + resource)
    return result


def generate():
    lines = [
        "// Generated by scripts/update_scout_icon_catalog.py. Do not edit by hand.",
        "// Source: " + BASE + "v1/items.json",
        "// Source: " + BASE + "v1/summoner-spells.json",
        "// Paths are bundled so cached Scout data needs no metadata request.",
        "const _base = '" + BASE + "';",
        "",
        "String? scoutItemIcon(int id) => _icon(_itemPaths[id]);",
        "String? scoutSpellIcon(int id) => _icon(_spellPaths[id]);",
        "String? _icon(String? path) => path == null ? null : '$_base$path';",
        "",
    ]
    for name, resource in [("_itemPaths", "items"), ("_spellPaths", "summoner-spells")]:
        entries = paths(resource)
        lines.append("const " + name + " = <int, String>{")
        for identity, path in sorted(entries.items()):
            lines.append("  " + str(identity) + ": '" + path.replace("'", "\\'") + "',")
        lines.extend(["};", ""])
        print(resource + ": " + str(len(entries)) + " icon paths")
    target = ROOT / "lib/domain/assets/scout_icon_catalog.dart"
    target.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    generate()
